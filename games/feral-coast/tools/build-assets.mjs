// Packs the CC0 models/textures the game uses into assets/assets.js (base64), so the game
// also runs when index.html is opened straight from disk (file:// cannot fetch() files).
// Usage: node build-assets.mjs <path to @netforge/asset-library-files/library>
import fs from 'node:fs';
import path from 'node:path';
const lib = process.argv[2];
if (!lib) { console.error('usage: node build-assets.mjs <library dir>'); process.exit(1); }
const MODELS = {
  soldier: 'lowpoly/soldier.glb', rebel1: 'lowpoly/adventurer.glb', rebel2: 'lowpoly/hooded_adventurer.glb',
  worker: 'lowpoly/worker.glb', pirate: 'lowpoly/pirate.glb',
  deer: 'lowpoly/deer.glb', stag: 'lowpoly/stag.glb', wolf: 'lowpoly/wolf.glb',
  suv: 'lowpoly/suv.glb', truck: 'lowpoly/truck.glb',
  palm: 'lowpoly/tree_palm.glb', oak: 'lowpoly/tree_oak.glb', treeFat: 'lowpoly/tree_fat.glb',
  bush: 'lowpoly/bush.glb', bushLarge: 'lowpoly/bush_large.glb', rock: 'lowpoly/rock_large.glb',
  rockTall: 'lowpoly/rock_tall.glb', stump: 'lowpoly/stump.glb', flower: 'lowpoly/flower_red.glb', log: 'lowpoly/log.glb',
  barrel: 'lowpoly/barrel.glb', crate: 'lowpoly/crate.glb', tent: 'lowpoly/tent.glb', campfire: 'lowpoly/campfire.glb',
  hangar: 'lowpoly/hangar.glb', dish: 'lowpoly/satellite_dish.glb', fence: 'lowpoly/fence.glb', generator: 'lowpoly/generator.glb',
  chest: 'lowpoly/chest.glb',
};
const TEXTURES = {
  grass: 'ps1/surface_grass.png', dirt: 'ps1/surface_dirt.png', stone: 'ps1/surface_stone.png', gravel: 'ps1/surface_gravel.png',
  wood: 'ps1/surface_wood.png', metal: 'ps1/surface_metal.png', concrete: 'ps1/surface_concrete.png', wall: 'ps1/surface_wall.png',
  bark: 'ps1/surface_bark.png',
};
// Extra CC0 Quaternius models (Toon Shooter Game Kit, Pirate Kit, Ultimate Animated Animals), converted
// with tools/gltf-to-glb.mjs and meshopt-compressed with gltf-transform; they live in assets/models/.
const EXTRA = {
  gunAK: 'ak.glb', gunPistol: 'pistol.glb', gunShotgun: 'shotgun.glb', gunSniper: 'sniper.glb', knife: 'knife_1.glb',
  grenade: 'grenade.glb', fireGrenade: 'firegrenade.glb', fox: 'fox.glb', shark: 'shark.glb',
  shipLarge: 'ship_large.glb', shipSmall: 'ship_small.glb', dock: 'dock.glb', dockBroken: 'dock_broken.glb',
  anchor: 'anchor.glb', cannon: 'cannon.glb', chestGold: 'chest_gold.glb',
  // CC BY models from Poly Pizza (see README credits)
  // FPS pack (Poly Pizza bundle): animated first-person arms + AKM / Glock, and the M939 truck
  // Kenney Watercraft / Car / Survival kits (CC0)
  kBoatRebel: 'k_boat_rebel.glb', kBoatTide: 'k_boat_tide.glb', kRowboat: 'k_rowboat.glb', kFishing: 'k_fishing.glb', kSedan: 'k_sedan.glb', kVan: 'k_van.glb',
  kWorkbench: 'k_workbench.glb', kCampfire: 'k_campfire.glb', kShelter: 'k_shelter.glb', kBedroll: 'k_bedroll.glb', kContainer: 'k_container.glb', kBuoy: 'k_buoy.glb',
  fpsAKM: 'fps_akm.glb', fpsGlock: 'fps_glock.glb', m939: 'm939.glb',
  croc: 'croc.glb', bear: 'bear.glb', jaguar: 'jaguar.glb', parrot: 'parrot.glb', radioTower: 'radio.glb', helicopter: 'helicopter.glb',
};
const out = { models: {}, textures: {} };
for (const [k, f] of Object.entries(MODELS)) out.models[k] = fs.readFileSync(path.join(lib, f)).toString('base64');
const here = path.dirname(new URL(import.meta.url).pathname);
for (const [k, f] of Object.entries(EXTRA)) out.models[k] = fs.readFileSync(path.join(here, '..', 'assets', 'models', f)).toString('base64');
for (const [k, f] of Object.entries(TEXTURES)) out.textures[k] = 'data:image/png;base64,' + fs.readFileSync(path.join(lib, f)).toString('base64');
const dest = path.join(path.dirname(new URL(import.meta.url).pathname), '..', 'assets', 'assets.js');
fs.writeFileSync(dest, '// Generated by tools/build-assets.mjs — CC0 art, see assets/CREDITS.md\nwindow.FC_ASSETS = ' + JSON.stringify(out) + ';\n');
console.log('wrote', dest, (fs.statSync(dest).size / 1048576).toFixed(2) + ' MB');
